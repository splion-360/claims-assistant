"""Fixed lines the agent speaks at the start and end of a sweep, and readers for short answers.

These lines carry numbers and settings that must be exact (the pricing market, the
packet totals), so they are written in code from configuration and the packet, never
generated by a language model.
"""
import re

from library_claim.config import CONFIG

SWEEP_EXPLANATION = ('Walk slowly along each shelf with the camera at spine height, then pan across the walls '
                     'and the floor. I will say what I log and tell you when something needs a closer look.')
AFFIRMATIVE = {'yes', 'yeah', 'yep', 'yup', 'correct', 'right', 'sure', 'ok', 'okay', 'exactly', 'indeed'}
# Words that turn an agreement into a disagreement or a condition.
HEDGES = {'no', 'not', 'nope', 'but', 'actually', 'wrong'}
ORIGINAL_WORDS = ('original', 'painted', 'oil painting', 'watercolour', 'watercolor', 'hand drawn',
                  'one of a kind', 'by the artist')


def _market(code: str):
    """Return a configured market's settings.

    Args:
        code: Country code.

    Returns:
        The market configuration.
    """
    return CONFIG.pricing.markets[code.upper()]


def _words(text: str) -> list[str]:
    """Split an utterance into lowercase words.

    Args:
        text: Utterance.

    Returns:
        Words without punctuation.
    """
    return re.findall(r"[a-z']+", text.casefold())


def _has_phrase(text: str, phrase: str) -> bool:
    """Say whether a phrase occurs as whole words.

    Short codes such as "US" or "UK" only count when written as a code (capitals or
    dotted), so the word "us" in "help us" is not read as a country.

    Args:
        text: Utterance.
        phrase: Alias or statement from configuration.

    Returns:
        True when the phrase is present.
    """
    if len(phrase) <= 3:
        dotted = r'\.?'.join(re.escape(letter) for letter in phrase.upper()) + r'\.?'
        return bool(re.search(rf'(?<![A-Za-z]){dotted}(?![A-Za-z])', text)) or text.strip(' .!').casefold() == phrase
    return bool(re.search(rf'(?<![a-z]){re.escape(phrase.casefold())}(?![a-z])', text.casefold()))


def greeting(default_country: str) -> str:
    """Open the sweep and ask the policyholder to confirm country and currency.

    Args:
        default_country: Configured default market.

    Returns:
        The greeting.
    """
    settings = _market(default_country)
    return (f'Hello, I will help you document your library for your contents claim. I will price everything '
            f'for {settings.name or default_country} in {settings.currency_name or settings.currency}. '
            f'Is that right, or which country are you in?')


def resolve_country(text: str, proposed: str) -> str | None:
    """Read a country confirmation from a spoken answer.

    Args:
        text: The policyholder's answer.
        proposed: Market the greeting proposed, confirmed by a plain "yes".

    Returns:
        The configured market code named or agreed to, or None when the answer does not settle it.
    """
    named = {code for code, settings in CONFIG.pricing.markets.items()
             if any(_has_phrase(text, alias) for alias in [code.lower(), *settings.aliases])}
    if len(named) == 1:
        return named.pop()
    if named:
        return None
    words = _words(text)
    # A short, unhedged agreement confirms the proposal; "yes, but France" does not.
    if words and len(words) <= 6 and AFFIRMATIVE & set(words) and not HEDGES & set(words):
        return proposed.upper()
    return None


def locale_confirmation(country: str) -> str:
    """Confirm the market and explain the sweep in two sentences.

    Args:
        country: Confirmed market code.

    Returns:
        The confirmation.
    """
    settings = _market(country)
    return (f'Thank you, I will price everything for {settings.name or country} in '
            f'{settings.currency_name or settings.currency}. {SWEEP_EXPLANATION}')


def art_question(item: dict) -> str:
    """Ask whether a framed piece is an original or a print.

    Args:
        item: Inventory entry of an art or mirror object.

    Returns:
        The question.
    """
    return f'Is that {item.get("description") or "framed piece"} an original or a print?'


def print_answer(text: str) -> str | None:
    """Read whether the policyholder said a framed piece is a print or an original.

    Args:
        text: The policyholder's answer.

    Returns:
        'print', 'original', or None when the answer says neither.
    """
    # Print wording is checked first, so "not an original" reads as a print.
    if any(_has_phrase(text, statement) for statement in CONFIG.items.print_statements):
        return 'print'
    if any(_has_phrase(text, word) for word in ORIGINAL_WORDS):
        return 'original'
    return None


def coverage_prompt(room: dict | None) -> str | None:
    """Ask for the part of the room the sweep did not look at, while the user is still there.

    Args:
        room: The measured room block, or None when it could not be measured.

    Returns:
        The request, or None when the sweep covered the room.
    """
    if room is None:
        return ('I could not measure the room from this sweep. Turn the camera back on and pan slowly '
                'across the walls and the floor.')
    coverage = room.get('yaw_coverage')
    if coverage is None or coverage >= CONFIG.measurement.room_min_coverage:
        return None
    return (f'I have only seen about {round(coverage * 100)}% of the room. Turn the camera back on and pan '
            f'across the walls you skipped.')


def _money(amount: float, currency: str) -> str:
    """Speak an amount with its currency.

    Args:
        amount: Figure from the packet totals.
        currency: ISO currency.

    Returns:
        E.g. "143.50 US dollars".
    """
    names = {code: settings.currency_name for code, settings in CONFIG.pricing.markets.items()
             if settings.currency_name}
    by_currency = {CONFIG.pricing.markets[code].currency: name for code, name in names.items()}
    return f'{amount:,.2f} {by_currency.get(currency, currency)}'


def summary(packet: dict) -> str:
    """Read back the claim packet's headline figures.

    Every number comes from the packet's totals, which code computed from its lines.

    Args:
        packet: A claim packet.

    Returns:
        The spoken summary.
    """
    totals, currency = packet['totals'], packet['sweep'].get('currency') or ''
    parts = [f'The sweep is complete. I logged {totals["book_count"]} books, {totals["books_identified"]} '
             f'identified and {totals["books_unidentified"]} I could not read, and {len(packet["items"])} '
             f'other items.']
    if totals['books_replacement_cost']:
        used = (f' and {_money(totals["books_used_value"], currency)} used' if totals['books_used_value'] else '')
        parts.append(f'The priced books come to {_money(totals["books_replacement_cost"], currency)} to replace '
                     f'new{used}.')
    else:
        parts.append('No book prices were found.')
    if totals['items_replacement_cost_high']:
        low, high = totals['items_replacement_cost_low'], totals['items_replacement_cost_high']
        parts.append(f'The other contents come to between {low:,.0f} and {_money(high, currency)}.'
                     if low != high else f'The other contents come to {_money(high, currency)}.')
    room = packet.get('room') or {}
    if room.get('floor_area_m2'):
        wall = f' and {room["wall_area_m2"]} square metres of wall' if room.get('wall_area_m2') else ''
        parts.append(f'The room is {room["floor_area_m2"]} square metres of floor{wall}.')
    else:
        parts.append('The room was not measured.')
    count = len(packet.get('review_queue') or [])
    parts.append(f'{count} lines need review. The claim packet is ready to download.' if count else
                 'Nothing needs review. The claim packet is ready to download.')
    return ' '.join(parts)
